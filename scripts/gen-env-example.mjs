import { readFileSync, writeFileSync } from "node:fs";

const data = JSON.parse(readFileSync("data/free-llm-apis.json", "utf8"));
const slug = (n) => n.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
const lines = ["# Generated by `npm run env:llm`. Copy to .env and fill in the keys you use.", ""];
for (const p of data.providers) {
  lines.push(`# ${p.name} - ${p.url}`);
  lines.push(`${slug(p.name).replace(/-/g, "_").toUpperCase()}_API_KEY=`);
}
lines.push("", "# Required for Cloudflare Workers AI", "CLOUDFLARE_ACCOUNT_ID=");
writeFileSync(".env.example", lines.join("\n") + "\n");
